const LANG = translations;

// Текущий язык (по умолчанию казахский)
let currentLang = localStorage.getItem('tm_lang') || 'kz';

function t(key) {
    return (translations[currentLang] && translations[currentLang][key]) || key;
}

function applyLang() {
    document.querySelectorAll('[data-lang]').forEach(function (el) {
        el.textContent = t(el.dataset.lang);
    });

    document.querySelectorAll('[data-lang-ph]').forEach(function (el) {
        el.placeholder = t(el.dataset.langPh);
    });

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
        btn.classList.toggle('active', btn.dataset.code === currentLang);
    });

    document.documentElement.lang = (currentLang === 'kz') ? 'kk' : 'ru';
}

function setLang(lang) {
    currentLang = lang;
    localStorage.setItem('tm_lang', lang);
    applyLang();

    if (typeof renderPage === 'function') {
        renderPage();
    }
}
