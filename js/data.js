async function payBooking(id, paymentMethod, paymentPlan) {
    const statusVal = (paymentPlan === 'prepay') ? 'partial' : 'paid';
    const bookings = load(KEYS.bookings);
    const booking = bookings.find(b => Number(b.id) === Number(id));
    if (booking) {
        booking.paymentStatus = statusVal;
        booking.paymentMethod = paymentMethod;
        booking.paidAt = new Date().toLocaleString('ru-RU');
        save(KEYS.bookings, bookings);
    } else {
        bookings.push({
            id: Number(id),
            paymentStatus: statusVal,
            paymentMethod: paymentMethod,
            paidAt: new Date().toLocaleString('ru-RU')
        });
        save(KEYS.bookings, bookings);
    }

    if (IS_SERVER_ENV) {
        await serverApi('bookings.php', 'pay', {
            id: Number(id),
            paymentMethod: paymentMethod + (paymentPlan === 'prepay' ? ' (30% Предоплата)' : '')
        });
    }
    return { ok: true, paymentStatus: statusVal };
}

async function setBookingStatus(id, status) {
    const bookings = load(KEYS.bookings);
    const booking = bookings.find(b => Number(b.id) === Number(id));
    if (booking) {
        booking.status = status;
        if (status === 'cancelled') booking.paymentStatus = (booking.paymentStatus === 'paid' || booking.paymentStatus === 'partial') ? 'refund' : 'unpaid';
        save(KEYS.bookings, bookings);
    }
    if (IS_SERVER_ENV) {
        const res = await serverApi('bookings.php', 'status', { id: Number(id), status: status });
        if (res && res.ok) return res;
    }
    return { ok: true };
}


