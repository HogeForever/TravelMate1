function saveTravelerProfile(profile, explicitUser) {
    const u = explicitUser || getCurrentUserSync();
    if (!u) return null;
    const all = load(KEYS.travelers);
    profile.userId = u.id;
    profile.userEmail = String(u.email || '').trim().toLowerCase();
    profile.userName = u.name || '';
    profile.fullName = String(profile.fullName || '').trim().toUpperCase();
    profile.passport = String(profile.passport || '').trim().toUpperCase();

    const existingIdx = all.findIndex(tr => {
        const sameUser = profile.userEmail
            ? String(tr.userEmail || '').trim().toLowerCase() === profile.userEmail
            : Number(tr.userId) === Number(u.id);
        const samePass = String(tr.passport || '').trim().toUpperCase() === profile.passport;
        return sameUser && samePass;
    });

    if (existingIdx !== -1) {
        all[existingIdx] = Object.assign({}, all[existingIdx], profile);
        save(KEYS.travelers, all);
    } else {
        profile.id = newId();
        all.unshift(profile);
        save(KEYS.travelers, all);
    }

    if (IS_SERVER_ENV) {
        serverApi('travelers.php', 'save', profile);
    }
    return profile;
}

