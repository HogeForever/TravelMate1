async function getCurrentUser() {
    if (IS_SERVER_ENV) {
        const res = await serverApi('auth.php', 'me');
        if (res && res.user) {
            localStorage.setItem(KEYS.currentUser, res.user.id);
            localStorage.setItem('tm_current_user_obj', JSON.stringify(res.user));
            return res.user;
        }
    }
    try {
        const savedObj = JSON.parse(localStorage.getItem('tm_current_user_obj') || 'null');
        if (savedObj && savedObj.id) return savedObj;
    } catch (e) {}

    const id = Number(localStorage.getItem(KEYS.currentUser));
    if (!id) return null;
    const users = await getUsers();
    return users.find(u => Number(u.id) === id) || null;
}

async function loginUser(email, password) {
    if (IS_SERVER_ENV) {
        const res = await serverApi('auth.php', 'login', { email: email, password: password });
        if (res && (res.ok || res.error)) {
            if (res.ok && res.user) {
                localStorage.setItem(KEYS.currentUser, res.user.id);
                localStorage.setItem('tm_current_user_obj', JSON.stringify(res.user));
            }
            return res;
        }
    }

    const user = load(KEYS.users).find(u => u.email === email && u.password === password);
    if (!user) return { ok: false, error: 'login_error' };
    if (user.status === 'blocked') return { ok: false, error: 'blocked_error' };

    localStorage.setItem(KEYS.currentUser, user.id);
    localStorage.setItem('tm_current_user_obj', JSON.stringify(user));
    return { ok: true, user: user };
}

async function registerUser(data) {
    if (IS_SERVER_ENV) {
        const res = await serverApi('auth.php', 'register', data);
        if (res && (res.ok || res.error)) {
            if (res.ok && res.user) {
                localStorage.setItem(KEYS.currentUser, res.user.id);
                localStorage.setItem('tm_current_user_obj', JSON.stringify(res.user));
            }
            return res;
        }
    }

    const users = load(KEYS.users);
    if (users.some(u => u.email === data.email)) {
        return { ok: false, error: 'email_exists' };
    }

    const user = {
        id: newId(),
        name: data.name,
        email: data.email,
        phone: data.phone,
        password: data.password,
        role: data.role,
        status: (data.role === 'agency') ? 'pending' : 'active'
    };

    users.push(user);
    save(KEYS.users, users);
    localStorage.setItem(KEYS.currentUser, user.id);
    localStorage.setItem('tm_current_user_obj', JSON.stringify(user));
    return { ok: true, user: user };
}

