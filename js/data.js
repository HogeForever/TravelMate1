/* ---------- Серверге (PHP) сұраныс жіберу көмекші функциясы ---------- */
async function serverApi(file, action, body) {
    try {
        const url = API_URL + file + (action ? '?action=' + encodeURIComponent(action) : '');
        const payload = Object.assign({}, body || {});

        try {
            const savedObj = JSON.parse(localStorage.getItem('tm_current_user_obj') || 'null');
            const savedId = Number(localStorage.getItem('tm_current_user')) || 0;
            if (savedObj && savedObj.email) payload._authEmail = savedObj.email;
            if (savedObj && savedObj.id) payload._authUserId = Number(savedObj.id);
            else if (savedId) payload._authUserId = savedId;
        } catch (e) {}

        const response = await fetch(url, {
            method: 'POST',
            credentials: 'same-origin',
            headers: { 'Content-Type': 'application/json; charset=utf-8' },
            body: JSON.stringify(payload)
        });

        if (!response.ok) {
            const errorText = await response.text();
            try { return JSON.parse(errorText); } catch (e) { return { ok: false, error: 'HTTP_' + response.status, message: errorText }; }
        }

        return await response.json();
    } catch (err) {
        console.warn('Сервермен байланыс қатесі, fallback режимі қосылады:', err);
        return null;
    }
}

