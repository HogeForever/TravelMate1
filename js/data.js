async function getBookings() {
    const localBookings = load(KEYS.bookings);
    if (IS_SERVER_ENV) {
        const res = await serverApi('bookings.php', 'list');
        if (Array.isArray(res)) {
            // Дополняем локальными полями оплаты/опций, если они были сохранены в браузере
            return res.map(b => {
                const localMatch = localBookings.find(lb => Number(lb.id) === Number(b.id));
                if (localMatch) {
                    if (!b.customOptions && localMatch.customOptions) b.customOptions = localMatch.customOptions;
                    if (localMatch.paymentStatus && localMatch.paymentStatus !== 'unpaid') b.paymentStatus = localMatch.paymentStatus;
                    if (localMatch.paymentMethod && !b.paymentMethod) b.paymentMethod = localMatch.paymentMethod;
                    if (localMatch.customTotal && (!b.total || b.total < localMatch.customTotal)) b.total = localMatch.customTotal;
                }
                return b;
            });
        }
    }
    const tours = load(KEYS.tours);
    const users = load(KEYS.users);
    const result = [];

    localBookings.forEach(booking => {
        const tour = tours.find(item => Number(item.id) === Number(booking.tourId)) || tours[0];
        const client = users.find(u => Number(u.id) === Number(booking.clientId));
        if (!tour) return;

        booking.tourTitle = tour.title;
        booking.agencyId = tour.agencyId;
        booking.total = booking.customTotal > 0 ? booking.customTotal : (tour.price * booking.people);
        booking.clientName = booking.clientName || (client ? client.name : 'Клиент');
        booking.clientPhone = booking.clientPhone || (client ? client.phone : '');
        booking.createdAtMs = booking.createdAtMs || Date.now();
        booking.paymentStatus = booking.paymentStatus || 'unpaid';
        result.push(booking);
    });

    return result;
}

